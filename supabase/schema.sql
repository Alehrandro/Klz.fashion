-- ---------- Cupons (só o admin lê; clientes validam pela função validate_coupon) ----------
create table if not exists public.coupons (
  code        text primary key check (code ~ '^[A-Z0-9]{2,30}$'),
  type        text not null check (type in ('pct','ship')),
  value       numeric(5,4) not null default 0 check (value >= 0 and value < 1),
  description text not null
);
alter table public.coupons enable row level security;

drop policy if exists coupons_admin on public.coupons;
create policy coupons_admin on public.coupons for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

-- ---------- Pedidos (clientes NÃO escrevem direto: usam a função place_order) ----------
create table if not exists public.orders (
  id            uuid primary key default gen_random_uuid(),
  number        text not null unique,
  created_at    timestamptz not null default now(),
  customer_name text not null,
  email         text not null,
  phone         text,
  address       jsonb not null default '{}'::jsonb,
  payment       text not null check (payment in ('Pix','Cartão','Boleto')),
  subtotal      numeric(10,2) not null,
  discount      numeric(10,2) not null default 0,
  shipping      numeric(10,2) not null default 0,
  total         numeric(10,2) not null,
  coupon_code   text,
  status        text not null default 'Novo' check (status in ('Novo','Pago','Enviado','Entregue','Cancelado')),
  items         jsonb not null
);
alter table public.orders enable row level security;

drop policy if exists orders_admin on public.orders;
create policy orders_admin on public.orders for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

-- ---------- Função: validar cupom ----------
create or replace function public.validate_coupon(p_code text)
returns jsonb language sql stable security definer set search_path = '' as $$
  select jsonb_build_object('type', type, 'value', value, 'description', description)
  from public.coupons where code = upper(trim(p_code));
$$;
grant execute on function public.validate_coupon(text) to anon, authenticated;

-- ---------- Função: finalizar pedido (preço, estoque, cupom e frete são calculados AQUI, no servidor) ----------
create or replace function public.place_order(p_customer jsonb, p_items jsonb, p_coupon text, p_payment text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_item   jsonb;
  v_prod   public.products%rowtype;
  v_cup    public.coupons%rowtype;
  v_cfg    jsonb;
  v_size   text;
  v_qty    int;
  v_avail  int;
  v_sub    numeric := 0;
  v_disc   numeric := 0;
  v_ship   numeric := 0;
  v_total  numeric;
  v_lines  jsonb := '[]'::jsonb;
  v_num    text;
  v_cep    text;
  v_free   numeric;
  v_rates  numeric[] := array[24.9,19.9,21.9,29.9,34.9,39.9,44.9,49.9,54.9,59.9];
begin
  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) not between 1 and 50 then
    raise exception 'Carrinho vazio ou inválido.';
  end if;
  if p_payment is null or p_payment not in ('Pix','Cartão','Boleto') then
    raise exception 'Forma de pagamento inválida.';
  end if;
  if char_length(coalesce(trim(p_customer->>'nome'), '')) not between 2 and 120 then
    raise exception 'Informe seu nome completo.';
  end if;
  if coalesce(p_customer->>'email', '') !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' or char_length(p_customer->>'email') > 160 then
    raise exception 'E-mail inválido.';
  end if;
  v_cep := regexp_replace(coalesce(p_customer->>'cep', ''), '\D', '', 'g');
  if char_length(v_cep) <> 8 then
    raise exception 'CEP inválido.';
  end if;

  select data into v_cfg from public.store_settings where id = 1;
  v_free := coalesce((v_cfg->>'frete')::numeric, 299);

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_size := v_item->>'s';
    v_qty  := (v_item->>'q')::int;
    if v_size is null or v_qty is null or v_qty < 1 or v_qty > 20 then
      raise exception 'Item inválido no carrinho.';
    end if;

    select * into v_prod from public.products where id = (v_item->>'id')::bigint for update;
    if not found then
      raise exception 'Um dos produtos não está mais disponível.';
    end if;

    v_avail := coalesce((v_prod.stock->>v_size)::int, 0);
    if v_avail < v_qty then
      raise exception 'Estoque insuficiente para "%" (tamanho %).', v_prod.name, v_size;
    end if;

    update public.products
       set stock = jsonb_set(stock, array[v_size], to_jsonb(v_avail - v_qty))
     where id = v_prod.id;

    v_sub   := v_sub + v_prod.price * v_qty;
    v_lines := v_lines || jsonb_build_array(jsonb_build_object('id', v_prod.id, 'n', v_prod.name, 's', v_size, 'q', v_qty, 'p', v_prod.price));
  end loop;

  if coalesce(trim(p_coupon), '') <> '' then
    select * into v_cup from public.coupons where code = upper(trim(p_coupon));
    if not found then raise exception 'Cupom inválido.'; end if;
    if v_cup.type = 'pct' then v_disc := round(v_sub * v_cup.value, 2); end if;
  end if;

  if v_cup.type is not distinct from 'ship' or (v_sub - v_disc) >= v_free then
    v_ship := 0;
  else
    v_ship := v_rates[substr(v_cep, 1, 1)::int + 1];
  end if;

  v_total := v_sub - v_disc + v_ship;
  if p_payment = 'Pix' then
    v_total := round(v_total * (1 - coalesce((v_cfg->>'pix')::numeric, 5) / 100), 2);
  end if;

  loop
    v_num := 'KLZ' || lpad((floor(random() * 900000) + 100000)::int::text, 6, '0');
    exit when not exists (select 1 from public.orders where number = v_num);
  end loop;

  insert into public.orders (number, customer_name, email, phone, address, payment, subtotal, discount, shipping, total, coupon_code, items)
  values (
    v_num, trim(p_customer->>'nome'), trim(p_customer->>'email'), left(p_customer->>'tel', 30),
    jsonb_build_object('cep', v_cep, 'num', left(p_customer->>'num', 20), 'end', left(p_customer->>'end', 200),
                       'bai', left(p_customer->>'bai', 100), 'cid', left(p_customer->>'cid', 100)),
    p_payment, v_sub, v_disc, v_ship, v_total, nullif(upper(trim(p_coupon)), ''), v_lines
  );

  return jsonb_build_object('number', v_num, 'total', v_total);
end;
$$;
grant execute on function public.place_order(jsonb, jsonb, text, text) to anon, authenticated;

-- ---------- Função: mudar status do pedido (admin; devolve/retira estoque ao cancelar/reabrir) ----------
create or replace function public.set_order_status(p_id uuid, p_status text)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_old  text;
  v_dir  int := 0;
  v_item jsonb;
begin
  if not public.is_admin() then raise exception 'Acesso negado.'; end if;
  if p_status not in ('Novo','Pago','Enviado','Entregue','Cancelado') then raise exception 'Status inválido.'; end if;

  select status into v_old from public.orders where id = p_id for update;
  if not found then raise exception 'Pedido não encontrado.'; end if;

  if p_status = 'Cancelado' and v_old <> 'Cancelado' then v_dir := 1;
  elsif v_old = 'Cancelado' and p_status <> 'Cancelado' then v_dir := -1;
  end if;

  if v_dir <> 0 then
    for v_item in select * from jsonb_array_elements((select items from public.orders where id = p_id)) loop
      update public.products
         set stock = jsonb_set(stock, array[v_item->>'s'],
                     to_jsonb(greatest(0, coalesce((stock->>(v_item->>'s'))::int, 0) + v_dir * (v_item->>'q')::int)))
       where id = (v_item->>'id')::bigint;
    end loop;
  end if;

  update public.orders set status = p_status where id = p_id;
end;
$$;
revoke execute on function public.set_order_status(uuid, text) from public, anon;
grant  execute on function public.set_order_status(uuid, text) to authenticated;

